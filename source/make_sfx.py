from sfxlib import *
def S(d):return np.zeros(int(SR*d))
# s01: Adam & Eve turn and smile (2.71s)
x=S(2.9);place(x,rustle(1.6),0.05,0.5);place(x,sparkle(1.2,6),1.25,0.35);save(norm(x),'audio2/s01.wav')
# s02: forbidden sign glows (6.04s)
x=S(6.0);h=hum(3.6);h*=np.clip((T(3.6)-0.0)/1.2,0,1)*np.clip((3.6-T(3.6))/1.6,0,1);place(x,h,0.4,0.35)
place(x,thud(55),0.45,0.8);place(x,thud(50),0.95,0.7);place(x,shimmer(1.6),0.5,0.4);save(norm(x),'audio2/s02.wav')
# s03: serpent turns to viewer (6.04s; big motion 2.8-5s)
x=S(6.0);place(x,slither(2.6),0.3,0.25);place(x,slither(2.0),2.8,0.5);place(x,hiss(1.4),3.2,0.9);place(x,hiss(0.8),4.6,0.5);save(norm(x),'audio2/s03.wav')
# s04: the bite, sky darkens (6.04s; bite ~3.2s)
x=S(6.0);place(x,wind(6.0,200,800),0,0.15);place(x,crunch(),3.15,1.0);place(x,thunder(2.6),3.5,0.9);place(x,wind(2.4,150,700),3.6,0.6);save(norm(x),'audio2/s04.wav')
# s05: leaving the garden, flaming sword (6.04s)
x=S(6.0);place(x,crackle(6.0,30),0,0.5);place(x,footsteps(3.6,rate=2.2,fade=3.6),0.3,0.7);place(x,whoosh(1.0),0.1,0.35);place(x,wind(6.0),0,0.25);save(norm(x),'audio2/s05.wav')
# s06: mirror of humanity (6.04s)
x=S(6.0);place(x,shimmer(1.4),0.1,0.6);place(x,crowd_steps(6.0,12),0,0.35);place(x,murmur(6.0,8),0,0.25);place(x,wind(6.0,120,500),0,0.2);save(norm(x),'audio2/s06.wav')
# s07: scrubbing at the murky water (5.04s)
x=S(5.0);place(x,trickle(5.0),0,0.4);place(x,splash(),0.15,0.6);place(x,scrub(1.6),0.3,0.6);place(x,scrub(1.4,5),2.1,0.55);place(x,splash(0.5),3.7,0.35);save(norm(x),'audio2/s07.wav')
print('sfx done')
